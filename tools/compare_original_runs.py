#!/usr/bin/env python3
"""Extract instruction-boundary DSJ traces and compare independent native runs.

Original records are <tag:u32,cs:u16,ds:u16,ip:u32,counter:u32>, then
the complete 65536-byte data segment. Tag1 is jump reset, tag2 follows
input polling, tag3 follows the controller and pose update. Numeric fields
are decoded directly from original memory, never generated by native code.
"""
import argparse
import csv
import gzip
import json
import math
import struct
from pathlib import Path

FIELDS = {
    'frame_counter': (0x4c50, 'I'), 'control_phase': (0x4c6b, 'B'),
    'countdown': (0x4c55, 'h'), 'start_hold_ticks': (0x5d1c, 'I'),
    'fall_bounce_count': (0x4c5e, 'B'),
    'x': (0x5248, 'f'), 'y': (0x5250, 'f'), 'vx': (0x5254, 'f'),
    'vy_down': (0x5258, 'f'), 'surface_speed': (0x525c, 'f'),
    'q': (0x4c6c, 'f'), 'hill_angle': (0x52a2, 'f'), 'work': (0x5294, 'f'),
    'start_y': (0x5288, 'f'), 'initial_speed': (0x528c, 'f'),
    'impulse_x': (0x4c84, 'f'), 'impulse_y': (0x4c88, 'f'),
    'flight_flag_byte': (0x5246, 'B'), 'launch_pending': (0x5247, 'B'),
    'rng_state': (0x18f2, 'I'), 'wind_x': (0x4cc0, 'f'), 'wind_y': (0x4cc4, 'f'),
    'wind_variation_step': (0x4cc8, 'f'), 'wind_speed': (0x4ccc, 'f'),
    'wind_angle': (0x4cd0, 'f'), 'wind_visual_angle': (0x4cd4, 'f'),
    'wind_angular_step': (0x4cd8, 'f'), 'wind_angular_cap': (0x4cdc, 'f'),
    'wind_cosmetic': (0x4ce0, 'B'), 'pose_mode': (0x52aa, 'H'),
    'pose_time': (0x52ac, 'f'), 'body_force_factor': (0x4cb6, 'f'),
    'leading_leg': (0x4c8c, 'B'), 'trim_left': (0x4c70, 'f'), 'trim_right': (0x4c74, 'f'),
    'aux_left': (0x4c78, 'f'), 'aux_right': (0x4c7c, 'f'),
    'flight_integral': (0x4c5a, 'f'), 'flight_duration': (0x4c5f, 'f'),
    'landing_timer': (0x4c63, 'f'), 'takeoff_duration': (0x4c67, 'f'),
    'landing_width': (0x4c8e, 'f'), 'impact_speed': (0x5299, 'f'),
    'impact_angle': (0x529d, 'f'), 'crash_kind': (0x4cb4, 'B'),
    'roughness': (0x4caa, 'h'), 'distance': (0x5242, 'f'), 'total': (0x5236, 'f'),
    'landing_complete': (0x4c58, 'B'),
    'ai_left': (0x3f0c, 'f'), 'ai_right': (0x3f10, 'f'), 'ai_delay': (0x3f14, 'f'),
    'ai_duration': (0x3f18, 'f'), 'ai_remaining': (0x3f1c, 'f'),
    'ai_target': (0x3f20, 'f'), 'ai_lead': (0x3f24, 'f'), 'ai_width': (0x3f28, 'f'),
    'ai_assess': (0x3f06, 'B'), 'ai_unusual': (0x3f07, 'B'),
}
for i in range(18):
    FIELDS[f'angle_{i}'] = (0x52c0+4*i if i<9 else 0x52ec+4*(i-9), 'f')
    FIELDS[f'angle_target_{i}'] = (0x5330+4*i, 'f')
    FIELDS[f'angle_rate_{i}'] = (0x5378+4*i, 'f')
for i in range(4):
    FIELDS[f'offset_{i}'] = (0x52b0+4*i, 'f')
    FIELDS[f'offset_target_{i}'] = (0x5320+4*i, 'f')
    FIELDS[f'offset_rate_{i}'] = (0x53c0+4*i, 'f')
for i in range(5):
    FIELDS[f'judge_{i}'] = (0x4bf4+0x109*(i+1), 'f')


def value(ds, off, kind):
    return struct.unpack_from('<'+kind, ds, off)[0]


def decode(ds):
    row = {name: value(ds, *location) for name, location in FIELDS.items()}
    row['leading_leg'] -= 1
    row['ai_mouse_dy'] = value(ds,0x4614,'h')
    row['ai_button_mask'] = bool(value(ds,0x4616,'B')) + 2*bool(value(ds,0x4617,'B'))
    row['style_points'] = sum(row[f'judge_{i}'] for i in range(5)
                              if value(ds, 0x4bf3+0x109*(i+1), 'B'))
    return row


def extract(trace, destination):
    destination.mkdir(parents=True, exist_ok=True)
    header = struct.Struct('<IHHII')
    inputs, states, boundaries = [], [], {}
    initial = None
    pre_ai_seed = None
    stopped = False
    opener = gzip.open if trace.suffix == '.gz' else open
    with opener(trace, 'rb') as stream:
        while raw := stream.read(header.size):
            if len(raw) != header.size:
                raise ValueError('Partial trace record header')
            tag, cs, ds_segment, ip, counter = header.unpack(raw)
            ds = stream.read(65536)
            if len(ds) != 65536:
                raise ValueError('Partial trace data segment')
            boundaries[str(tag)] = {'cs': cs, 'ip': ip, 'ds': ds_segment}
            if tag == 1:
                if initial is not None:
                    raise ValueError('More than one jump in trace; split at initialization')
                initial = ds
                states.append(decode(ds))
            elif tag == 2:
                inputs.append({'counter': counter,
                               'button_mask': bool(value(ds, 0x4616, 'B')) + 2*bool(value(ds, 0x4617, 'B')),
                               'mouse_dy': max(-128, min(127, value(ds, 0x4614, 'h')))})
            elif tag == 3:
                row=decode(ds)
                if not inputs or inputs[-1]['counter']!=counter:
                    raise ValueError(f'Missing input-poll boundary at original counter{counter}')
                # Controller/replay callbacks can clear the original button
                # bytes. Compare CPU choices with the actual precontroller poll.
                row['ai_button_mask']=inputs[-1]['button_mask']
                row['ai_mouse_dy']=inputs[-1]['mouse_dy']
                states.append(row)
                if (value(ds,0x4c58,'B') and not value(ds,0x5246,'B')
                        and value(ds,0x525c,'f') <= .01):
                    stopped=True
                    break  # Subsequent scoreboard frames do not poll/step.
            elif tag == 4:
                pre_ai_seed = value(ds,0x18f2,'I')
    if initial is None or not inputs or len(states) != len(inputs)+1:
        raise ValueError(f'Incomplete full trace: initial={initial is not None}, inputs={len(inputs)}, states={len(states)}')
    if states[0]['frame_counter'] != 1 or any(row['frame_counter'] != i+1 for i, row in enumerate(states)):
        raise ValueError('Missing or duplicate original ticks')
    (destination/'initial.ds.bin').write_bytes(initial)
    for name, rows in [('inputs.csv', inputs), ('original.csv', states)]:
        with (destination/name).open('w') as stream:
            writer=csv.DictWriter(stream, fieldnames=rows[0].keys())
            writer.writeheader(); writer.writerows(rows)
    metadata={'frames': len(states), 'boundaries': boundaries,
              'initial_seed': value(initial, 0x18f2, 'I'),
              'pre_ai_seed': pre_ai_seed,
              'physical_stop': stopped,
              'complete_ticks': True, 'first_counter': 1, 'last_counter': states[-1]['frame_counter']}
    ai_player=value(initial,0x57f4,'B')
    metadata.update({'active_player': value(initial,0x4c4d,'B'), 'ai_player': ai_player,
                     'ai_initializer_guard': value(initial,0x5bb9,'B'),
                     'fast_advance': value(initial,0x296e,'B'),
                     'ai_skills': {'level': value(initial,0x5bfb+17*ai_player+16,'B'),
                                   'values': [value(initial,0x5bfb+17*ai_player+4*i,'f') for i in range(4)]}})
    (destination/'capture.json').write_text(json.dumps(metadata, indent=2)+'\n')
    print(json.dumps(metadata))


def compare(original, native, output, tolerance, cpu=False):
    with original.open() as stream:
        expected=list(csv.DictReader(stream))
    with native.open() as stream:
        actual=list(csv.DictReader(stream))
    # AI fields are validated separately when a CPU was configured.
    fields=[name for name in expected[0] if name in actual[0] and (cpu or not name.startswith('ai_'))]
    results={name: {'mismatches': 0, 'maximum_absolute_error': 0} for name in fields}
    first=[]
    for row_index, (before, after) in enumerate(zip(expected, actual)):
        for name in fields:
            if row_index==0 and name in ('ai_mouse_dy','ai_button_mask'):
                continue  # Initial bytes still belong to the menu input poll.
            a,b=float(before[name]),float(after[name])
            difference=abs(a-b)
            if a==b or (math.isnan(a) and math.isnan(b)):
                continue
            item=results[name]
            item['mismatches']+=1
            item['maximum_absolute_error']=max(item['maximum_absolute_error'], difference)
            if 'first' not in item:
                item['first']={'counter': before['frame_counter'], 'original': a, 'native': b}
            if len(first)<40:
                first.append({'counter': before['frame_counter'], 'field': name, 'original': a, 'native': b})
    failures={name: result for name,result in results.items()
              if result['mismatches'] and (FIELDS.get(name,(0,''))[1]!='f' or result['maximum_absolute_error']>tolerance)}
    report={'original_frames': len(expected), 'native_frames': len(actual),
            'compared_fields': len(fields), 'absolute_float_tolerance': tolerance,
            'passed': not failures and len(expected)==len(actual), 'fields': results,
            'first_differences': first, 'failures': list(failures)}
    output.write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps({key:report[key] for key in ('passed','original_frames','native_frames','compared_fields','failures','first_differences')}))
    return 0 if report['passed'] else 1


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    commands=parser.add_subparsers(dest='command',required=True)
    command=commands.add_parser('extract')
    command.add_argument('trace',type=Path); command.add_argument('destination',type=Path)
    command=commands.add_parser('compare')
    command.add_argument('original',type=Path); command.add_argument('native',type=Path)
    command.add_argument('output',type=Path); command.add_argument('--tolerance',type=float,default=0)
    command.add_argument('--cpu',action='store_true')
    args=parser.parse_args()
    if args.command=='extract':
        extract(args.trace,args.destination)
    else:
        raise SystemExit(compare(args.original,args.native,args.output,args.tolerance,args.cpu))
