#!/usr/bin/env python3
"""Rebuild the bundled flag atlas from Flagpedia's Wikimedia-derived images.
Development tool only; requires network access and ffmpeg, neither at runtime.
"""
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
# Order is stable: the first 32 follow the original game's hill catalog.
NATIONS = [
    ('FIN', 'Finland', 'fi'), ('SUI', 'Switzerland', 'ch'),
    ('CZE', 'Czech Rep.', 'cz'), ('BLR', 'Belarus', 'by'),
    ('AUT', 'Austria', 'at'), ('USA', 'USA', 'us'),
    ('LAT', 'Latvia', 'lv'), ('POL', 'Poland', 'pl'),
    ('JPN', 'Japan', 'jp'), ('BEL', 'Belgium', 'be'),
    ('ISL', 'Iceland', 'is'), ('ENG', 'England', 'gb-eng'),
    ('GER', 'Germany', 'de'), ('EST', 'Estonia', 'ee'),
    ('NOR', 'Norway', 'no'), ('AUS', 'Australia', 'au'),
    ('IRL', 'Ireland', 'ie'), ('UKR', 'Ukraine', 'ua'),
    ('HUN', 'Hungary', 'hu'), ('SWE', 'Sweden', 'se'),
    ('ITA', 'Italy', 'it'), ('DEN', 'Denmark', 'dk'),
    ('SVK', 'Slovakia', 'sk'), ('CAN', 'Canada', 'ca'),
    ('LTU', 'Lithuania', 'lt'), ('KAZ', 'Kazakhstan', 'kz'),
    ('CHN', 'China', 'cn'), ('FRA', 'France', 'fr'),
    ('NED', 'Netherlands', 'nl'), ('RUS', 'Russia', 'ru'),
    ('KOR', 'South Korea', 'kr'), ('SLO', 'Slovenia', 'si'),
    ('GBR', 'United Kingdom', 'gb'),
]
CELL, COLS = 88, 6
WIDTH, HEIGHT = CELL * COLS, CELL * ((len(NATIONS) + COLS - 1) // COLS)

def download(nation):
    code, name, iso = nation
    url = f'https://flagcdn.com/w80/{iso}.png'
    with urlopen(url, timeout=30) as response:
        png = response.read()
    assert png[:8] == b'\x89PNG\r\n\x1a\n'
    w, h = struct.unpack('>II', png[16:24])
    assert 1 < w <= 80 and 1 < h <= 80
    return nation, png, w, h, url

def main():
    atlas = bytearray(WIDTH * HEIGHT * 3)
    manifest, entries = [], []
    with ThreadPoolExecutor(max_workers=6) as executor:
        sources = list(executor.map(download, NATIONS))
    with tempfile.TemporaryDirectory(prefix='perfect-v-flags-') as tmp:
        for i, (nation, png, w, h, url) in enumerate(sources):
            path = Path(tmp) / (nation[2] + '.png')
            path.write_bytes(png)
            rgb = subprocess.check_output([
                'ffmpeg', '-v', 'error', '-i', str(path), '-f', 'rawvideo',
                '-pix_fmt', 'rgb24', '-frames:v', '1', '-'])
            assert len(rgb) == w * h * 3
            x, y = (i % COLS) * CELL + 4, (i // COLS) * CELL + 4
            # Replicate the edge into a two-pixel gutter for linear sampling.
            for row in range(-2, h + 2):
                for col in range(-2, w + 2):
                    source = (max(0, min(h - 1, row)) * w + max(0, min(w - 1, col))) * 3
                    target = ((y + row) * WIDTH + x + col) * 3
                    atlas[target:target + 3] = rgb[source:source + 3]
            code, name, iso = nation
            entries.append(f'    {{"{code}", "{name}", "{iso}", {x}, {y}, {w}, {h}}},')
            manifest.append(dict(code=code, country=name, source=url, width=w, height=h,
                                 sha256=hashlib.sha256(png).hexdigest()))
    # Top-down 24-bit BMP; SDL3 can load it without another image dependency.
    stride = (WIDTH * 3 + 3) & ~3
    pixels = bytearray(stride * HEIGHT)
    for y in range(HEIGHT):
        for x in range(WIDTH):
            src, dst = (y * WIDTH + x) * 3, y * stride + x * 3
            pixels[dst:dst + 3] = atlas[src:src + 3][::-1]
    header = b'BM' + struct.pack('<IHHI', 54 + len(pixels), 0, 0, 54)
    header += struct.pack('<IiiHHIIiiII', 40, WIDTH, -HEIGHT, 1, 24, 0, len(pixels), 2835, 2835, 0, 0)
    destination = ROOT / 'assets' / 'flags'
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'atlas.bmp').write_bytes(header + pixels)
    (destination / 'sources.json').write_text(json.dumps(manifest, indent=2) + '\n')
    (ROOT / 'src' / 'nationalities.inc').write_text(
        '// Generated by tools/generate_flag_atlas.py; artwork coordinates and native aspect ratios.\n'
        + '\n'.join(entries) + '\n')
    print(f'Bundled {len(NATIONS)} flags: {WIDTH} x {HEIGHT}, {len(header + pixels)} bytes')

if __name__ == '__main__':
    main()
